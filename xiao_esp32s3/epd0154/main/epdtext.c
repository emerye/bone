// Low-Level SPI Operations
void epd_write_command(uint8_t command) {  
    gpio_set_level(EPD_DC_PIN, 0);
    spi_transaction_t t = { .length = 8, .tx_buffer = &command };
    spi_device_polling_transmit(spi_handle, &t);
}

void epd_write_data(uint8_t data) {
    gpio_set_level(EPD_DC_PIN, 1);
    spi_transaction_t t = { .length = 8, .tx_buffer = &data };
    spi_device_polling_transmit(spi_handle, &t);
}

void epd_wait_busy(void) {
    while (gpio_get_level(EPD_BUSY_PIN) == 1) {
        vTaskDelay(pdMS_TO_TICKS(10));
    }
}

// Driver Hardware Configurations
void epd_init(void) {
    gpio_set_level(EPD_RST_PIN, 0);
    vTaskDelay(pdMS_TO_TICKS(20));
    gpio_set_level(EPD_RST_PIN, 1);
    vTaskDelay(pdMS_TO_TICKS(20));
    epd_wait_busy();

    // SW Reset
    epd_write_command(0x12);
    epd_wait_busy();

    // Driver Output control
    epd_write_command(0x01);
    epd_write_data((EPD_HEIGHT - 1) & 0xFF);
    epd_write_data(((EPD_HEIGHT - 1) >> 8) & 0xFF);
    epd_write_data(0x00);

    // Data Entry Mode
    epd_write_command(0x11);
    epd_write_data(0x03);

    // RAM X Position Settings
    epd_write_command(0x44);
    epd_write_data(0x00);
    epd_write_data((EPD_WIDTH / 8) - 1);

    // RAM Y Position Settings
    epd_write_command(0x45);
    epd_write_data(0x00);
    epd_write_data(0x00);
    epd_write_data((EPD_HEIGHT - 1) & 0xFF);
    epd_write_data(((EPD_HEIGHT - 1) >> 8) & 0xFF);

    // Border Waveform Setup
    epd_write_command(0x3C);
    epd_write_data(0x05);

    // Update Mode Options
    epd_write_command(0x22);
    epd_write_data(0x91);
    epd_write_command(0x20);
    epd_wait_busy();
}

void epd_display_frame(const uint8_t *buffer) {
    // Reset RAM Counters
    epd_write_command(0x4E);
    epd_write_data(0x00);
    epd_write_command(0x4F);
    epd_write_data(0x00);
    epd_write_data(0x00);

    // Flush Memory Bus Bytes
    epd_write_command(0x24);
    for (int i = 0; i < BUFFER_SIZE; i++) {
        epd_write_data(buffer[i]);
    }

    // Refresh display
    epd_write_command(0x22);
    epd_write_data(0xF7);
    epd_write_command(0x20);
    epd_wait_busy();
}

void epd_sleep(void) {
    epd_write_command(0x10);
    epd_write_data(0x01);
}

// Canvas Painting Operations
void draw_pixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= EPD_WIDTH || y < 0 || y >= EPD_HEIGHT) return;
    int index = (x / 8) + (y * (EPD_WIDTH / 8));
    uint8_t bit_mask = (0x80 >> (x % 8));
    if (color == 0) {
        image_buffer[index] &= ~bit_mask;
    } else {
        image_buffer[index] |= bit_mask;
    }
}

void draw_rectangle(int x1, int y1, int x2, int y2, uint8_t color) {
    for (int x = x1; x <= x2; x++) {
        draw_pixel(x, y1, color);
        draw_pixel(x, y2, color);
    }
    for (int y = y1; y <= y2; y++) {
        draw_pixel(x1, y, color);
        draw_pixel(x2, y, color);
    }
}

void draw_char(int x, int y, char c, uint8_t color, int size) {
    if (c < 32 || c > 126) return;
    int font_idx = c - 32;


    for (int row = 0; row < 8; row++) {
        uint8_t row_data = font8x8[font_idx][row];
        for (int col = 0; col < 8; col++) {
            if (row_data & (0x80 >> col)) {
                for (int sx = 0; sx < size; sx++) {
                    for (int sy = 0; sy < size; sy++) {
                        int target_x = x + (col * size) + sx;
                        int target_y = y + (row * size) + sy;
                        draw_pixel(target_x, target_y, color);
                    }
                }
            }
        }
    }
}

void draw_string(int x, int y, const char *str, uint8_t color, int size) {
    while (*str) {
        draw_char(x, y, *str, color, size);
        x += 8 * size;
        str++;
    }
}


// --- Graphical Utilities Supporting the "font_bitmap_64px" Array ---

// Renders a single 32x64 clock symbol from the font_bitmap_64px array
void draw_clock_char(int x, int y, char c, uint8_t color) {
    int idx = -1;

    // Map characters to array indices: digits 0-9 match indices 0-9, colon is 10
    if (c >= '0' && c <= '9') {
        idx = c - '0';
    } else if (c == ':') {
        idx = 10;
    }

    // Abort if the character is outside our custom font map range
    if (idx == -1) return;

    for (int row = 0; row < 64; row++) {
        for (int byte_col = 0; byte_col < 4; byte_col++) {
            // Unpack 4 bytes sequentially to cover 32 horizontal pixels per row
            // Indexing format: [character_index][row_byte_offset]
            uint8_t byte_data = font_bitmap_64px[(idx * 256) + (row * 4) + byte_col];

            for (int bit = 0; bit < 8; bit++) {
                if (byte_data & (0x80 >> bit)) {
                    int target_x = x + (byte_col * 8) + bit;
                    int target_y = y + row;
                    draw_pixel(target_x, target_y, color);
                }
            }
        }
    }
}


// Iterates through string arrays to pass structured character layouts to the canvas

void draw_clock_string(int x, int y, const char *str, uint8_t color) {
    while (*str) {
        draw_clock_char(x, y, *str, color);
        // Step forward by exactly 32 horizontal pixels for the next clock element
        x += 32;
        str++;
    }
}


