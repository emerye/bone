// System Startup Location
void app_main(void)
{
    ESP_LOGI(TAG, "Starting up...");

    // Setup control lines
    gpio_config_t io_conf = {
        .pin_bit_mask = (1ULL << EPD_DC_PIN) | (1ULL << EPD_RST_PIN),
        .mode = GPIO_MODE_OUTPUT,
    };
    gpio_config(&io_conf);

    // Setup feedback input
    gpio_config_t input_conf = {
        .pin_bit_mask = (1ULL << EPD_BUSY_PIN),
        .mode = GPIO_MODE_INPUT,
        .pull_up_en = GPIO_PULLUP_ENABLE,
    };
    gpio_config(&input_conf);

    // Setup SPI Configuration
    spi_bus_config_t buscfg = {
        .mosi_io_num = EPD_MOSI_PIN,
        .miso_io_num = -1,
        .sclk_io_num = EPD_SCLK_PIN,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = BUFFER_SIZE};
    spi_device_interface_config_t devcfg = {
        .clock_speed_hz = 4 * 1000 * 1000,
        .mode = 0,
        .spics_io_num = EPD_CS_PIN,
        .queue_size = 1,
        .flags = SPI_DEVICE_HALFDUPLEX};
    ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));
    ESP_ERROR_CHECK(spi_bus_add_device(SPI2_HOST, &devcfg, &spi_handle));
    // Fill screen buffer with White baseline (0xFF)
    memset(image_buffer, 0xFF, sizeof(image_buffer));
    // Outer framing box
    draw_rectangle(15, 15, 185, 185, 0);
    // Display centered text

    //draw_string(20, 90, "Hello World", 0, 2);
    //draw_string(20, 110, "Hello There", 0, 2);

     draw_clock_string(20, 68, "1", 0);


    // Hardware Push Initialization Sequence
    epd_init();
    ESP_LOGI(TAG, "Writing text frame to panel...");
    epd_display_frame(image_buffer);
    // Put controller to deep sleep
    ESP_LOGI(TAG, "Entering panel deep sleep state.");
    epd_sleep();
}
